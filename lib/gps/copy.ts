export type GpsCopy = (typeof gpsCopy)[PanelLocale];

export function gpsErrorText(copy: GpsCopy, code: string | undefined) {
  if (code === "imei") return copy.errorImei;
  if (code === "vehicle") return copy.errorVehicle;
  if (code === "failed") return copy.errorFailed;
  if (code === "forbidden") return copy.errorForbidden;
  if (code === "wifi") return copy.errorWifi;
  if (code === "range") return copy.errorRange;
  if (code === "invalid") return copy.errorInvalid;
  if (code === "device_code") return copy.errorDeviceCode;
  if (code === "device_used") return copy.deleteUsed;
  if (code === "telemetry") return copy.errorInvalid;
  return "";
}
